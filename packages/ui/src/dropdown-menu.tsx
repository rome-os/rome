import * as React from "react";
import * as DropdownMenuPrimitive from "@radix-ui/react-dropdown-menu";
import { cva } from "class-variance-authority";
import { Check, ChevronRight } from "lucide-react";

import { cn } from "./cn.js";
import { AutoPortal } from "./portal.js";

/**
 * Exported so a surface that renders menu rows *outside* a menu root can wear
 * the treatment without the semantics — `DropdownMenuItem` misbehaves outside
 * a `DropdownMenu`, so the mobile action sheet owns its own element. Colors
 * key off `data-variant` / `data-disabled`, so a plain
 * `<button data-variant="destructive">` matches without restating them.
 */
const dropdownMenuItemVariants = cva(
  "group/dropdown-menu-item relative flex cursor-default items-center outline-hidden select-none focus:bg-accent focus:text-accent-foreground not-data-[variant=destructive]:focus:**:text-accent-foreground data-inset:pl-8 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive dark:data-[variant=destructive]:focus:bg-destructive/20 data-disabled:pointer-events-none data-disabled:opacity-50 disabled:pointer-events-none disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 data-[variant=destructive]:*:[svg]:text-destructive",
  {
    variants: {
      // `touch` carries hover and focus-visible because a Radix item gets both
      // from the menu — hover moves focus, and keyboard position is unambiguous
      // within an open menu — while a standalone button gets neither. The
      // accent background alone is ~1.2:1 against the sheet surface, well under
      // the 3:1 WCAG 1.4.11 wants from a focus indicator, so the outline is the
      // real indicator and the background is only a highlight. `outline-solid`
      // is required: the base's `outline-hidden` sets --tw-outline-style: none,
      // and `outline-2` reads that variable.
      //
      // Keep both out of the base: a caller overriding only `focus:bg-*`
      // (AppsIndexPage's uninstall items) would face a base `hover:bg-*` of
      // equal specificity, leaving stylesheet order to pick.
      size: {
        default: "gap-2 rounded-8 px-2 py-1 text-ui [&_svg:not([class*='size-'])]:size-4",
        touch:
          "min-h-12 w-full gap-3 rounded-8 px-3 py-2 text-left text-ui transition-colors hover:bg-accent hover:text-accent-foreground not-data-[variant=destructive]:hover:**:text-accent-foreground data-[variant=destructive]:hover:bg-destructive/10 data-[variant=destructive]:hover:text-destructive dark:data-[variant=destructive]:hover:bg-destructive/20 outline-1 outline-offset-0 outline-transparent focus-visible:outline-solid focus-visible:-outline-offset-2 focus-visible:outline-ring/50 [&_svg:not([class*='size-'])]:size-5",
      },
    },
    defaultVariants: { size: "default" },
  },
);

function DropdownMenu({ ...props }: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  return <DropdownMenuPrimitive.Root data-slot="dropdown-menu" {...props} />;
}

/**
 * Escape hatch for menu content rendered outside `DropdownMenuContent` (which
 * portals on its own). Children only — the container is resolved, and Radix's
 * `forceMount` has no consumer here.
 */
function DropdownMenuPortal({ children }: { children?: React.ReactNode }) {
  return <AutoPortal portal={DropdownMenuPrimitive.Portal}>{children}</AutoPortal>;
}

function DropdownMenuTrigger({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Trigger>) {
  return <DropdownMenuPrimitive.Trigger data-slot="dropdown-menu-trigger" {...props} />;
}

function DropdownMenuContent({
  className,
  align = "start",
  sideOffset = 4,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content>) {
  return (
    <AutoPortal portal={DropdownMenuPrimitive.Portal}>
      <DropdownMenuPrimitive.Content
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        align={align}
        className={cn(
          "z-50 max-h-(--radix-dropdown-menu-content-available-height) min-w-32 origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-12 bg-popover p-1 text-popover-foreground shadow-4 ring-1 ring-foreground/10 duration-100 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=closed]:overflow-hidden data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:fade-out-0 data-closed:zoom-out-95",
          className,
        )}
        {...props}
      />
    </AutoPortal>
  );
}

function DropdownMenuGroup({ ...props }: React.ComponentProps<typeof DropdownMenuPrimitive.Group>) {
  return <DropdownMenuPrimitive.Group data-slot="dropdown-menu-group" {...props} />;
}

function DropdownMenuItem({
  className,
  inset,
  variant = "default",
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Item> & {
  inset?: boolean;
  variant?: "default" | "destructive";
}) {
  return (
    <DropdownMenuPrimitive.Item
      data-slot="dropdown-menu-item"
      data-inset={inset}
      data-variant={variant}
      className={cn(dropdownMenuItemVariants(), className)}
      {...props}
    />
  );
}

